import { readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "smol-toml";

const here = dirname(fileURLToPath(import.meta.url));
const themesDir = resolve(here, "../../themes");
const outFile = resolve(here, "../lib/themes.ts");

const DEFAULT_BUTTONS = ["#ff5f57", "#febc2e", "#28c840"];
const FEATURED = ["tokyonight", "catppuccin", "gruvbox", "nord"];

const LABELS = {
  tokyonight: "Tokyo Night",
  catppuccin: "Catppuccin",
  "catppuccin-mocha": "Catppuccin Mocha",
  "catppuccin-macchiato": "Catppuccin Macchiato",
  "catppuccin-frappe": "Catppuccin Frappé",
  "catppuccin-latte": "Catppuccin Latte",
  gruvbox: "Gruvbox",
  nord: "Nord",
  dracula: "Dracula",
  solarized: "Solarized",
  onedark: "One Dark",
  monokai: "Monokai",
  everforest: "Everforest",
  kanagawa: "Kanagawa",
  "rose-pine": "Rosé Pine",
  github: "GitHub",
};

function palette(raw) {
  if (!raw) return null;
  const buttons = raw.buttons ?? DEFAULT_BUTTONS;
  return {
    fg: raw.fg,
    bg: raw.bg,
    cursor: raw.cursor ?? raw.fg,
    chrome: raw.chrome ?? raw.bg,
    border: raw.border ?? raw.bg,
    buttons: [buttons[0], buttons[1], buttons[2]],
    ansi: raw.ansi,
  };
}

function relativeLuminance(hex) {
  const channel = (value) => {
    const c = value / 255;
    return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  };
  const h = hex.replace("#", "");
  const r = channel(parseInt(h.slice(0, 2), 16));
  const g = channel(parseInt(h.slice(2, 4), 16));
  const b = channel(parseInt(h.slice(4, 6), 16));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

const files = readdirSync(themesDir).filter((f) => f.endsWith(".toml"));

const themes = files.map((file) => {
  const slug = file.replace(/\.toml$/, "");
  const raw = parse(readFileSync(join(themesDir, file), "utf8"));
  const dark = palette(raw.dark);
  const light = palette(raw.light);
  return {
    slug,
    label: LABELS[slug] ?? slug,
    dark,
    light,
    isLight: relativeLuminance(dark.bg) > 0.5,
  };
});

themes.sort((a, b) => {
  const ai = FEATURED.indexOf(a.slug);
  const bi = FEATURED.indexOf(b.slug);
  if (ai !== -1 || bi !== -1) {
    return (ai === -1 ? 99 : ai) - (bi === -1 ? 99 : bi);
  }
  return a.label.localeCompare(b.label);
});

const banner = `// Generated by scripts/build-themes.mjs from ../themes/*.toml. Do not edit.\n\n`;

const types = `export type Palette = {
  fg: string;
  bg: string;
  cursor: string;
  chrome: string;
  border: string;
  buttons: [string, string, string];
  ansi: string[];
};

export type Theme = {
  slug: string;
  label: string;
  dark: Palette;
  light: Palette | null;
  isLight: boolean;
};

`;

const body = `export const THEMES: Theme[] = ${JSON.stringify(themes, null, 2)};

export const DEFAULT_THEME = "tokyonight";

export function paletteFor(theme: Theme, mode: "light" | "dark"): Palette {
  if (mode === "light" && theme.light) return theme.light;
  return theme.dark;
}

export function paletteVars(palette: Palette): Record<string, string> {
  const vars: Record<string, string> = {
    "--bg": palette.bg,
    "--fg": palette.fg,
    "--cur": palette.cursor,
    "--chrome": palette.chrome,
    "--border": palette.border,
  };
  palette.buttons.forEach((color, i) => {
    vars["--btn" + i] = color;
  });
  palette.ansi.forEach((color, i) => {
    vars["--c" + i] = color;
  });
  return vars;
}
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, banner + types + body);
console.log(`themes: wrote ${themes.length} to lib/themes.ts`);

