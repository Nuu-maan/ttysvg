import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, "../../docs/demo.svg");
const outFile = resolve(here, "../lib/hero-svg.ts");

const PREFIX = "ts-";
const BUTTONS = ["#ff5f57", "#febc2e", "#28c840"];

let svg = readFileSync(source, "utf8");

const styleMatch = svg.match(/<style>([\s\S]*?)<\/style>/);
if (!styleMatch) throw new Error("demo.svg has no <style> block");

let css = styleMatch[1];

css = css
  .replace(/^:root\{[^}]*\}/, "")
  .replace(/@media\(prefers-color-scheme:light\)\{:root\{[^}]*\}\}/, "")
  .replace(/:root\[data-theme="(?:light|dark)"\]\{[^}]*\}/g, "");

const classNames = [...css.matchAll(/\.([a-zA-Z][\w-]*)\s*\{/g)].map((m) => m[1]);
const keyframeNames = [...css.matchAll(/@keyframes\s+([\w-]+)/g)].map((m) => m[1]);

for (const name of new Set(classNames)) {
  css = css.replaceAll(`.${name}{`, `.${PREFIX}${name}{`);
}
for (const name of new Set(keyframeNames)) {
  css = css.replaceAll(`@keyframes ${name}`, `@keyframes ${PREFIX}${name}`);
  css = css.replaceAll(`animation:${name} `, `animation:${PREFIX}${name} `);
}

let body = svg.slice(styleMatch.index + styleMatch[0].length);

body = body.replace(/class="([^"]+)"/g, (_, value) => {
  const renamed = value
    .split(/\s+/)
    .map((c) => `${PREFIX}${c}`)
    .join(" ");
  return `class="${renamed}"`;
});

BUTTONS.forEach((hex, i) => {
  body = body.replaceAll(`"${hex}"`, `"var(--btn${i})"`);
});

const head = svg.slice(0, styleMatch.index);
const viewBox = head.match(/viewBox="([\d.\s-]+)"/)?.[1];
if (!viewBox) throw new Error("demo.svg has no viewBox");
const [, , width, height] = viewBox.split(/\s+/).map(Number);

const finalOffset = [...css.matchAll(/translateY\((-?[\d.]+)px\)/g)]
  .map((m) => Number(m[1]))
  .reduce((min, n) => Math.min(min, n), 0);

const animatedClass = classNames.find((name) => css.includes(`.${PREFIX}${name}{animation:`));
if (animatedClass) {
  css += `@media(prefers-reduced-motion:reduce){.${PREFIX}${animatedClass}{animation:none;transform:translateY(${finalOffset}px)}}`;
}

let openTag = head.replace(/\s(width|height)="[^"]*"/g, "");
openTag = openTag.replace(
  /<svg /,
  `<svg preserveAspectRatio="xMidYMin meet" style="width:100%;height:auto;display:block" `,
);

const markup = `${openTag}<style>${css}</style>${body}`;

const out = `// Generated by scripts/build-hero.mjs from ../docs/demo.svg. Do not edit.

export const HERO_WIDTH = ${width};
export const HERO_HEIGHT = ${height};
export const HERO_ASPECT = "${width} / ${height}";
export const HERO_SVG = ${JSON.stringify(markup)};
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, out);
console.log(
  `hero: ${(markup.length / 1024).toFixed(1)} KB, ${width}x${height}, reduced-motion frame at ${finalOffset}px`,
);
